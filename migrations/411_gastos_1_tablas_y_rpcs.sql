-- =========================================================================
-- 411 · GASTOS 1 · VEHICULOS, RUBROS Y GASTOS (entrega 1 de 5)
--
-- Diseno: docs/superpowers/specs/2026-10-28-gastos-y-cuentas-del-personal-design.md
-- Plan:   docs/superpowers/plans/2026-10-28-gastos-1-vehiculos-rubros-y-gastos.md
--
-- La app mide hasta la contribucion ("antes de gastos fijos"). Para el estado
-- de resultados (#1269) faltan los gastos: desde el combustible de un vehiculo
-- hasta la libreria. Esta migracion los registra; la pantalla del resultado no
-- es de este proyecto.
--
-- QUE AGREGA
--   * vehiculos (por sucursal, patente unica normalizada) y vehiculo_km: las
--     lecturas de km por vehiculo y dia, con su origen (manual, carga de
--     combustible o gps). La conexion con el GPS (#1270) escribe ahi.
--   * gasto_rubros: GLOBAL (como cargo_conceptos, 278). Cada rubro pertenece a
--     un grupo fijo, que es el renglon del resultado. Ninguno es un sueldo: los
--     sueldos salen de las liquidaciones (entregas 3 y 4). El grupo no cambia
--     una vez que el rubro tiene gastos, y pide_litros_km no se apaga si tiene
--     cargas con litros o km. Semilla con los 18 rubros del spec.
--   * gastos: un gasto con rubro, comprobante, sucursal (o la marca
--     compartido), mes del gasto y reparto en N meses. No se borra: se anula.
--     neto, costo y mes_fin son columnas generadas:
--       costo = total - IVA - percepciones   (va al resultado)
--       neto  = costo - otros impuestos      (otros = no recuperables, ITC)
--     Solo factura A o M lleva desglose (CHECK gastos_desglose_check).
--   * RPCs del front (SECURITY DEFINER, validan rol y sucursal adentro):
--     guardar_vehiculo, registrar_km_vehiculo, guardar_rubro_gasto,
--     guardar_gasto, anular_gasto. Los mensajes dicen que hacer.
--   * De server: gastos_por_mes (la expansion por mes y cuota que consume el
--     estado de resultados), _gasto_cuota (la pura de cuotas; replica
--     cuotaDeGasto de src/utils/gastos.ts, mismos ejemplos en el ensayo, sin
--     gate de paridad) y _tiene_todas_las_sucursales.
--
-- QUIEN VE Y HACE QUE (lo valida el server; el front solo esconde)
--   Admin de una sucursal: ve, carga, edita y anula los gastos de sus
--     sucursales; carga compartidos y ve todos los compartidos; edita o anula
--     un compartido solo si lo cargo el o si tiene TODAS las sucursales
--     activas; con la misma regla vuelve compartido un gasto que no lo era.
--     Crea y edita rubros; da de alta y de baja vehiculos.
--   Encargado: carga gastos de la sucursal en la que esta, sin compartido; ve
--     los de su sucursal que no son compartidos; edita y anula solo los suyos.
--     No crea rubros. Lee los vehiculos de su sucursal para elegirlos, y sus
--     lecturas de km (el modal precarga la del combustible que edita).
--   El resto de los roles: nada.
--
-- COMPARTIDO: la fila guarda la sucursal donde se cargo (aislamiento por
-- sucursal, FKs compuestas) mas la marca. El reparto entre sucursales segun lo
-- vendido es del estado de resultados; gastos_por_mes devuelve el compartido a
-- cualquier lista de sucursales.
--
-- ORIGEN DEL PAGO: la columna admite oficina, rendicion y empleado, pero en
-- esta entrega guardar_gasto rechaza todo lo que no sea oficina. La rendicion
-- (entrega 2) y el empleado (entrega 3) se habilitan sin cambiar la firma:
-- el gasto viaja en un jsonb.
--
-- PERMISOS (#1135, #1151): tablas con RLS, SELECT por policy TO authenticated,
-- sin escritura REST y sin nada para anon; secuencias sin grants (nadie
-- inserta por REST). scripts/grants-rest.json no cambia. Funciones del front:
-- REVOKE PUBLIC, anon; las de server, ademas authenticated.
--
-- ORDEN DE DESPLIEGUE: esta migracion ANTES que el front. La vista Gastos lee
-- las tablas por REST y llama las RPCs: sin ellas falla entera.
-- =========================================================================

