-- 3 · Gastos
-- -------------------------------------------------------------------------
CREATE TABLE public.gastos (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sucursal_id        bigint NOT NULL REFERENCES public.sucursales(id),
  compartido         boolean NOT NULL DEFAULT false,
  fecha              date NOT NULL,
  rubro_id           bigint NOT NULL REFERENCES public.gasto_rubros(id),
  monto_total        numeric(14,2) NOT NULL CHECK (monto_total > 0),
  comprobante        text NOT NULL CHECK (comprobante IN
    ('factura_a', 'factura_m', 'factura_b', 'factura_c', 'recibo', 'ticket', 'ninguno')),
  comprobante_numero text,
  alicuota_iva       numeric(4,1) CHECK (alicuota_iva IS NULL OR alicuota_iva IN (21, 10.5, 27)),
  iva                numeric(14,2) NOT NULL DEFAULT 0 CHECK (iva >= 0),
  percepcion_iva     numeric(14,2) NOT NULL DEFAULT 0 CHECK (percepcion_iva >= 0),
  percepcion_iibb    numeric(14,2) NOT NULL DEFAULT 0 CHECK (percepcion_iibb >= 0),
  otros_impuestos    numeric(14,2) NOT NULL DEFAULT 0 CHECK (otros_impuestos >= 0),
  neto               numeric(14,2) GENERATED ALWAYS AS
                       (monto_total - iva - percepcion_iva - percepcion_iibb - otros_impuestos) STORED,
  costo              numeric(14,2) GENERATED ALWAYS AS
                       (monto_total - iva - percepcion_iva - percepcion_iibb) STORED,
  vehiculo_id        bigint,
  litros             numeric(10,2) CHECK (litros IS NULL OR litros > 0),
  mes_imputado       date NOT NULL CHECK (mes_imputado = date_trunc('month', mes_imputado::timestamp)::date),
  repartir_meses     integer NOT NULL DEFAULT 1 CHECK (repartir_meses BETWEEN 1 AND 120),
  mes_fin            date GENERATED ALWAYS AS
                       ((mes_imputado + make_interval(months => repartir_meses - 1))::date) STORED,
  origen_pago        text NOT NULL DEFAULT 'oficina' CHECK (origen_pago IN ('oficina', 'rendicion', 'empleado')),
  observacion        text,
  creado_por         uuid NOT NULL,
  anulado_at         timestamptz,
  anulado_por        uuid,
  motivo_anulacion   text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT gastos_id_sucursal_key UNIQUE (id, sucursal_id),
  CONSTRAINT gastos_vehiculo_fkey
    FOREIGN KEY (vehiculo_id, sucursal_id) REFERENCES public.vehiculos (id, sucursal_id),
  CONSTRAINT gastos_desglose_check CHECK (
    comprobante IN ('factura_a', 'factura_m')
    OR (iva = 0 AND percepcion_iva = 0 AND percepcion_iibb = 0 AND otros_impuestos = 0 AND alicuota_iva IS NULL)),
  CONSTRAINT gastos_neto_positivo CHECK (
    monto_total - iva - percepcion_iva - percepcion_iibb - otros_impuestos > 0),
  CONSTRAINT gastos_anulacion_check CHECK (
    (anulado_at IS NULL AND anulado_por IS NULL AND motivo_anulacion IS NULL)
    OR (anulado_at IS NOT NULL AND anulado_por IS NOT NULL AND btrim(COALESCE(motivo_anulacion, '')) <> ''))
);
CREATE INDEX gastos_sucursal_mes_idx ON public.gastos (sucursal_id, mes_imputado);
CREATE INDEX gastos_mes_fin_idx ON public.gastos (mes_fin);
CREATE INDEX gastos_vehiculo_idx ON public.gastos (vehiculo_id);
CREATE INDEX gastos_rubro_idx ON public.gastos (rubro_id);

COMMENT ON TABLE public.gastos IS
  'Gastos de la distribuidora (gastos 1/5). No se borran: se anulan. Se escriben por guardar_gasto y anular_gasto.';
COMMENT ON COLUMN public.gastos.compartido IS
