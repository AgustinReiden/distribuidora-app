-- El usuario tiene asignadas TODAS las sucursales activas (el "admin de las
-- dos" del spec): puede tocar un compartido que no cargo.
CREATE OR REPLACE FUNCTION public._tiene_todas_las_sucursales()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $fn$
  SELECT auth.uid() IS NOT NULL
     AND NOT EXISTS (
       SELECT 1 FROM sucursales s
        WHERE s.activa
          AND NOT EXISTS (SELECT 1 FROM usuario_sucursales us
                           WHERE us.usuario_id = auth.uid() AND us.sucursal_id = s.id));
$fn$;

-- La cuota k (1..n) de un costo repartido en n meses: las primeras n-1 valen
-- round(costo / n, 2) y la ultima absorbe el redondeo. Replica cuotaDeGasto de
-- src/utils/gastos.ts: 100 en 3 da 33,33 / 33,33 / 33,34; 1.320.000 en 12 da
-- 110.000 cada una. Fuera de rango, NULL.
CREATE OR REPLACE FUNCTION public._gasto_cuota(p_costo numeric, p_n integer, p_k integer)
RETURNS numeric
LANGUAGE sql
IMMUTABLE
SET search_path = public
AS $fn$
  SELECT CASE
    WHEN p_costo IS NULL OR p_n IS NULL OR p_k IS NULL OR p_n < 1 OR p_k < 1 OR p_k > p_n THEN NULL
    WHEN p_k < p_n THEN round(p_costo / p_n, 2)
    ELSE p_costo - round(p_costo / p_n, 2) * (p_n - 1)
  END;
$fn$;

-- La expansion que consume el estado de resultados (#1269): un renglon por
-- gasto vivo y por mes de su reparto, entre el mes de p_desde y p_hasta. Trae
-- los gastos de p_sucursales y TODOS los compartidos (el reparto entre
-- sucursales es del resultado). Los anulados no cuentan.
CREATE OR REPLACE FUNCTION public.gastos_por_mes(p_desde date, p_hasta date, p_sucursales bigint[])
RETURNS TABLE (mes date, gasto_id bigint, sucursal_id bigint, compartido boolean, grupo text, rubro_id bigint,
               vehiculo_id bigint, cuota integer, cuotas integer, costo numeric)
LANGUAGE sql
STABLE
SET search_path = public
AS $fn$
  WITH v AS (SELECT date_trunc('month', p_desde::timestamp)::date AS desde)
  SELECT c.mes, g.id, g.sucursal_id, g.compartido, r.grupo, g.rubro_id, g.vehiculo_id,
         c.k, g.repartir_meses, public._gasto_cuota(g.costo, g.repartir_meses, c.k)
    FROM v
    JOIN public.gastos g ON g.mes_fin >= v.desde AND g.mes_imputado <= p_hasta
    JOIN public.gasto_rubros r ON r.id = g.rubro_id
   CROSS JOIN LATERAL (
     SELECT s.k, (g.mes_imputado + make_interval(months => s.k - 1))::date AS mes
       FROM generate_series(1, g.repartir_meses) AS s(k)) c
   WHERE g.anulado_at IS NULL
     AND (g.sucursal_id = ANY(p_sucursales) OR g.compartido)
     AND c.mes >= v.desde AND c.mes <= p_hasta
   ORDER BY c.mes, g.id;
$fn$;

-- -------------------------------------------------------------------------
-- 7 · RPCs del front
-- -------------------------------------------------------------------------
-- Alta y edicion de un vehiculo (admin). p_vehiculo: {id?, patente,
-- descripcion, activo?}. La patente se normaliza aca. El alta va en la
-- sucursal activa; la edicion, sobre un vehiculo de una sucursal del usuario.
-- En la edicion, la clave que no viene conserva su valor.
CREATE OR REPLACE FUNCTION public.guardar_vehiculo(p_vehiculo jsonb)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $fn$
DECLARE
  v_uid      uuid := auth.uid();
  v_id       bigint;
  v_suc      bigint;
  v_viejo    vehiculos%ROWTYPE;
  v_patente  text;
  v_desc     text;
  v_activo   boolean;
BEGIN
  IF NOT public.es_admin() THEN
    RAISE EXCEPTION 'Sólo un admin puede dar de alta o editar vehículos';
  END IF;
  IF jsonb_typeof(p_vehiculo) IS DISTINCT FROM 'object' THEN
    RAISE EXCEPTION 'Faltan los datos del vehículo';
  END IF;
  BEGIN
    v_id := NULLIF(p_vehiculo->>'id', '')::bigint;
    v_activo := (p_vehiculo->>'activo')::boolean;
  EXCEPTION WHEN others THEN
    RAISE EXCEPTION 'Hay un dato del vehículo con un formato inválido';
  END;

  IF v_id IS NOT NULL THEN
    SELECT * INTO v_viejo FROM vehiculos
     WHERE id = v_id
       AND sucursal_id IN (SELECT us.sucursal_id FROM usuario_sucursales us WHERE us.usuario_id = v_uid)
       FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Ese vehículo no es de una de tus sucursales';
    END IF;
  END IF;

  v_patente := CASE WHEN v_id IS NULL OR p_vehiculo ? 'patente'
                    THEN upper(regexp_replace(COALESCE(p_vehiculo->>'patente', ''), '[^A-Za-z0-9]', '', 'g'))
                    ELSE v_viejo.patente END;
  v_desc := CASE WHEN v_id IS NULL OR p_vehiculo ? 'descripcion'
                 THEN btrim(COALESCE(p_vehiculo->>'descripcion', ''))
                 ELSE v_viejo.descripcion END;
  v_activo := COALESCE(v_activo, CASE WHEN v_id IS NULL THEN true ELSE v_viejo.activo END);

  IF v_patente !~ '^[A-Z0-9]{6,8}$' THEN
    RAISE EXCEPTION 'La patente tiene que tener de 6 a 8 letras o números, como AC456EF o ABC123';
  END IF;
  IF v_desc = '' THEN
    RAISE EXCEPTION 'Escribí qué vehículo es, por ejemplo "Partner blanca"';
  END IF;

  BEGIN
    IF v_id IS NULL THEN
      v_suc := public.current_sucursal_id();
      IF v_suc IS NULL THEN
        RAISE EXCEPTION 'No se pudo determinar la sucursal activa';
      END IF;
      INSERT INTO vehiculos (sucursal_id, patente, descripcion, activo, creado_por)
      VALUES (v_suc, v_patente, v_desc, v_activo, v_uid)
      RETURNING id INTO v_id;
    ELSE
      UPDATE vehiculos
         SET patente = v_patente, descripcion = v_desc, activo = v_activo, updated_at = now()
       WHERE id = v_id;
    END IF;
  EXCEPTION WHEN unique_violation THEN
    RAISE EXCEPTION 'Ya hay un vehículo con la patente %', v_patente;
  END;

  RETURN v_id;
END
$fn$;

