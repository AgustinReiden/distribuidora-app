GRANT EXECUTE ON FUNCTION public.guardar_gasto(jsonb) TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.anular_gasto(bigint, text) TO authenticated, service_role;

-- -------------------------------------------------------------------------
-- 9 · Verificacion estructural
-- -------------------------------------------------------------------------
DO $verif$
DECLARE
  f text;
  t regclass;
BEGIN
  FOREACH f IN ARRAY ARRAY['public._tiene_todas_las_sucursales()', 'public._gasto_cuota(numeric,integer,integer)',
                           'public.gastos_por_mes(date,date,bigint[])'] LOOP
    IF has_function_privilege('anon', f, 'EXECUTE') OR has_function_privilege('authenticated', f, 'EXECUTE') THEN
      RAISE EXCEPTION '% quedo alcanzable desde el front', f;
    END IF;
  END LOOP;
  FOREACH f IN ARRAY ARRAY['public.guardar_vehiculo(jsonb)', 'public.registrar_km_vehiculo(bigint,date,integer)',
                           'public.guardar_rubro_gasto(jsonb)', 'public.guardar_gasto(jsonb)',
                           'public.anular_gasto(bigint,text)'] LOOP
    IF has_function_privilege('anon', f, 'EXECUTE') OR NOT has_function_privilege('authenticated', f, 'EXECUTE') THEN
      RAISE EXCEPTION 'los EXECUTE de % no quedaron como se esperaba', f;
    END IF;
  END LOOP;
  FOREACH t IN ARRAY ARRAY['public.vehiculos', 'public.vehiculo_km', 'public.gasto_rubros', 'public.gastos']::regclass[] LOOP
    IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid = t) THEN
      RAISE EXCEPTION '% sin RLS', t;
    END IF;
    IF has_table_privilege('anon', t, 'SELECT')
       OR has_table_privilege('authenticated', t, 'INSERT') OR has_table_privilege('authenticated', t, 'UPDATE')
       OR has_table_privilege('authenticated', t, 'DELETE') THEN
      RAISE EXCEPTION '% quedo con privilegios de mas', t;
    END IF;
  END LOOP;
  IF public._gasto_cuota(100, 3, 1) <> 33.33 OR public._gasto_cuota(100, 3, 3) <> 33.34
     OR public._gasto_cuota(1320000, 12, 12) <> 110000 THEN
    RAISE EXCEPTION '_gasto_cuota no da lo de cuotaDeGasto';
  END IF;
  IF (SELECT count(*) FROM public.gasto_rubros) <> 18 THEN
    RAISE EXCEPTION 'la semilla de rubros no quedo en 18';
  END IF;
END
$verif$;
